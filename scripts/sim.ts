/**
 * Offline economy simulation. Judges can rerun it:
 *   npm run sim                      # 30 days, seed 42, 4 AI guilds, 50 bot players
 *   npm run sim -- --days 60 --seed 7
 * Writes docs/economy-sim.md and docs/img/sim-*.svg from the actual run.
 */
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  createVillage, fmt, NPCS, NPC_DEFS, ITEMS, ITEM_DEFS, RULES, ReplayWorld, type WorldDay, type DailyStats,
} from '../packages/economy/src/index.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name: string, def: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : def;
};
const days = Number(arg('days', '30'));
const seed = Number(arg('seed', '42'));
const bots = Number(arg('bots', '50'));
const worldKind = arg('world', 'synthetic');

const world = worldKind === 'replay'
  ? new ReplayWorld((JSON.parse(readFileSync(join(root, 'data/world/replay-kansas-heatwave.json'), 'utf8')) as { days: WorldDay[] }).days)
  : undefined;

const v = createVillage({ seed, botPlayers: bots, world });
const flows = () => {
  const L0 = v.s.ledger;
  return L0.faucets.exports + L0.faucets.adventurers + L0.faucets.quests + L0.faucets.signup - (L0.sinks.feeBurn + L0.sinks.imports + L0.sinks.upkeep);
};
const genesis = v.goldSupply() - flows();
v.runDays(days);
const st = v.s.dailyStats;
const L = v.s.ledger;

const faucets = L.faucets.exports + L.faucets.adventurers + L.faucets.quests + L.faucets.signup;
const sinks = L.sinks.feeBurn + L.sinks.imports + L.sinks.upkeep;
const gap = v.goldSupply() - (genesis + faucets - sinks);
const maxBroke = Math.max(0, ...NPCS.map((id) => maxStreak(st, id)));
const idx = st.map((d) => (d.priceIndex / st[0].priceIndex) * 100); // day 1 = 100
const idxMin = Math.min(...idx);
const idxMax = Math.max(...idx);
const supply0 = st[0].goldSupply;
const supplyN = st[st.length - 1].goldSupply;
const half = Math.floor(st.length / 2);
const growthFirst = (st[half].goldSupply - supply0) / supply0;
const growthSecond = (supplyN - st[half].goldSupply) / st[half].goldSupply;

function maxStreak(stats: DailyStats[], id: string) {
  let best = 0;
  let cur = 0;
  for (const d of stats) {
    cur = d.broke.includes(id as never) ? cur + 1 : 0;
    best = Math.max(best, cur);
  }
  return best;
}

function svgLine(title: string, values: number[], opts: { baseline?: number; color: string; fmtY: (n: number) => string }) {
  const W = 640, H = 240, P = 40;
  const lo = Math.min(...values, opts.baseline ?? Infinity);
  const hi = Math.max(...values, opts.baseline ?? -Infinity);
  const pad = (hi - lo) * 0.1 || 1;
  const y = (n: number) => H - P - ((n - (lo - pad)) / (hi - lo + 2 * pad)) * (H - 2 * P);
  const x = (i: number) => P + (i / Math.max(1, values.length - 1)) * (W - 2 * P);
  const pts = values.map((n, i) => `${x(i).toFixed(1)},${y(n).toFixed(1)}`).join(' ');
  const base = opts.baseline !== undefined
    ? `<line x1="${P}" x2="${W - P}" y1="${y(opts.baseline)}" y2="${y(opts.baseline)}" stroke="#8a8f98" stroke-dasharray="4 4"/>`
    : '';
  const ticks = [lo, (lo + hi) / 2, hi].map((t) => `<text x="${P - 6}" y="${y(t) + 4}" text-anchor="end" font-size="11" fill="#8a8f98">${opts.fmtY(t)}</text>`).join('');
  const xt = values.map((_, i) => (i % 5 === 0 || i === values.length - 1 ? `<text x="${x(i)}" y="${H - P + 16}" text-anchor="middle" font-size="11" fill="#8a8f98">D${i + 1}</text>` : '')).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" font-family="ui-monospace, monospace">
<rect width="${W}" height="${H}" fill="#1e2130"/>
<text x="${P}" y="22" font-size="13" fill="#e6e6e6">${title}</text>
${base}${ticks}${xt}
<polyline fill="none" stroke="${opts.color}" stroke-width="2.5" points="${pts}"/>
</svg>`;
}

mkdirSync(join(root, 'docs/img'), { recursive: true });
writeFileSync(join(root, 'docs/img/sim-gold-supply.svg'), svgLine('Gold supply (gold)', st.map((d) => d.goldSupply / 100), { color: '#e3a83b', fmtY: (n) => n.toFixed(0) }));
writeFileSync(join(root, 'docs/img/sim-price-index.svg'), svgLine('Village price index (day 1 = 100)', idx, { baseline: 100, color: '#8db8ff', fmtY: (n) => n.toFixed(0) }));

const ranking = v.ranking();
const pass = (b: boolean) => (b ? 'PASS' : 'FAIL');
const md = `# Economy simulation report

Generated by \`npm run sim -- --days ${days} --seed ${seed} --bots ${bots} --world ${worldKind}\` on the engine in
\`packages/economy\`. Every number below comes from that run; rerun the command to reproduce it exactly
(the engine is deterministic for a given seed).

Setup: 6 NPCs, 4 AI guilds (${Object.values(v.s.guilds).filter((x) => x.ai).map((x) => x.name).join(', ')}),
${bots} bot players, ${days} game days, ${worldKind} world weather. Rules: \`packages/economy/src/defs.ts\`.

## Checks

| Check | Result | Value |
| --- | --- | --- |
| Gold is conserved (supply = genesis + faucets - sinks) | ${pass(gap === 0)} | gap ${gap} centigold |
| No NPC bankrupt for more than 2 days in a row | ${pass(maxBroke <= 2)} | longest streak ${maxBroke} days |
| Village price index stays within ±12% of day 1 | ${pass(idxMin >= 88 && idxMax <= 112)} | min ${idxMin.toFixed(1)}, max ${idxMax.toFixed(1)} |
| Gold supply growth | info | first half ${(growthFirst * 100).toFixed(1)}%, second half ${(growthSecond * 100).toFixed(1)}% |

![Gold supply](img/sim-gold-supply.svg)

![Village price index](img/sim-price-index.svg)

## Gold flows over the run

| Flow | Gold |
| --- | ---: |
| Faucet: Bruno's exports to the world market | +${fmt(L.faucets.exports, 0)} |
| Faucet: travelling adventurers buying swords | +${fmt(L.faucets.adventurers, 0)} |
| Faucet: quest rewards | +${fmt(L.faucets.quests, 0)} |
| Faucet: starting gold of new players | +${fmt(L.faucets.signup, 0)} |
| Sink: market fee burn (0.75% of volume) | -${fmt(L.sinks.feeBurn, 0)} |
| Sink: Bruno's imports paid to the world | -${fmt(L.sinks.imports, 0)} |
| Sink: NPC workshop upkeep | -${fmt(L.sinks.upkeep, 0)} |
| Season pool income (0.75% of volume + stall rent) | ${fmt(L.feesToPool, 0)} |
| Market volume | ${fmt(L.volume, 0)} |
| Goods sinks | ${L.toolsWorn} tools worn out, ${L.breadEaten} bread eaten |

## Final prices (gold per unit)

| Item | Village | World | Market stock / target |
| --- | ---: | ---: | ---: |
${ITEMS.map((i) => `| ${ITEM_DEFS[i].name} | ${fmt(st[st.length - 1].prices[i])} | ${st[st.length - 1].world[i] ? fmt(st[st.length - 1].world[i]!) : '-'} | ${v.s.market.stock[i]} / ${ITEM_DEFS[i].target} |`).join('\n')}

## NPC balances (gold)

| NPC | Day 1 | Day ${Math.ceil(days / 2)} | Day ${days} |
| --- | ---: | ---: | ---: |
${NPCS.map((id) => `| ${NPC_DEFS[id].name} (${NPC_DEFS[id].title}) | ${fmt(st[0].npcGold[id], 0)} | ${fmt(st[half].npcGold[id], 0)} | ${fmt(st[st.length - 1].npcGold[id], 0)} |`).join('\n')}

## Guild ranking at the end

| # | Guild | Return on fund | Members |
| --- | --- | ---: | ---: |
${ranking.slice(0, 10).map((r, i) => `| ${i + 1} | ${r.name} | ${(r.score * 100).toFixed(1)}% | ${r.members} |`).join('\n')}

Season length is ${RULES.seasonDays} days; returns restart from the fund value at each season close.

## Daily series

| Day | Gold supply | Price index | Wheat | Ore | Bread | Sword |
| ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${st.map((d) => `| ${d.day} | ${fmt(d.goldSupply, 0)} | ${idx[d.day - st[0].day].toFixed(1)} | ${fmt(d.prices.wheat)} | ${fmt(d.prices.ore)} | ${fmt(d.prices.bread)} | ${fmt(d.prices.sword)} |`).join('\n')}
`;

writeFileSync(join(root, 'docs/economy-sim.md'), md);
const summary = `${days} simulated days, 4 AI guilds, ${bots} bot players: gold conserved to the centigold, longest NPC bankruptcy ${maxBroke} days, price index ${idxMin.toFixed(0)}–${idxMax.toFixed(0)} (day 1 = 100), gold supply ${growthFirst >= 0 ? '+' : ''}${(growthFirst * 100).toFixed(1)}% then ${growthSecond >= 0 ? '+' : ''}${(growthSecond * 100).toFixed(1)}% per half.`;
writeFileSync(join(root, 'apps/client/public/sim-summary.json'), JSON.stringify({ text: summary, days, seed, bots }, null, 2) + '\n');
console.log(`days=${days} seed=${seed} gap=${gap} maxBroke=${maxBroke} index=[${idxMin.toFixed(1)}, ${idxMax.toFixed(1)}] supply ${fmt(supply0, 0)} -> ${fmt(supplyN, 0)}`);
console.log('wrote docs/economy-sim.md');
if (gap !== 0 || maxBroke > 2) process.exitCode = 1;
